"""Audio licence gate: every audio asset used in a video must have a licence entry with proof, or delivery fails.

Assets: the voice model, each music mood, each ambience bed, each SFX. Music, ambience and SFX are generated by our own code
(factory/synth.py, factory/musiclib.py), so no third-party recording exists and no Content ID claim is possible.
python -m factory.licence --write   regenerates docs/LICENCES.md and library/audio_licences.json
"""
from __future__ import annotations

import json
import os
import sys

from . import synth

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OWN_PROOF = "docs/licences/OWN-WORK-CC0.txt"
MIT_PROOF = "docs/licences/chatterbox-MIT.txt"
AMBIENCE = ("room", "city", "wind", "hum_dark")


def _own(where: str) -> dict:
    return {"source": f"generated in repo ({where})", "licence": "own work, dedicated CC0 1.0", "attribution_required": False, "proof": OWN_PROOF}


def entries() -> dict:
    e = {}
    for name in synth.SFX_GAIN:
        e[f"sfx:{name}"] = _own("factory/synth.py sfx()")
    for kind in AMBIENCE:
        e[f"ambience:{kind}"] = _own("factory/synth.py ambience()")
    for mood in synth.MOOD:
        e[f"music:{mood}"] = _own("factory/synth.py render_music(), factory/musiclib.py")
    mit = {"source": "https://github.com/resemble-ai/chatterbox (model ResembleAI/chatterbox on Hugging Face)", "licence": "MIT",
           "attribution_required": False, "proof": MIT_PROOF,
           "note": "Chatterbox applies Resemble's Perth implicit watermark inside generate(); factory/tts.py never disables it"}
    e["voice:chatterbox"] = dict(mit)
    e["voice:chatterbox_turbo"] = dict(mit)
    return e


def used_assets(audio_plan: dict, assemble_report: dict) -> list:
    u = {f"sfx:{x['name']}" for x in audio_plan.get("sfx", [])}
    u |= {f"ambience:{x['kind']}" for x in audio_plan.get("ambience", [])}
    u |= {f"music:{x['mood']}" for x in audio_plan.get("music", [])}
    u |= {f"voice:{x}" for x in (assemble_report.get("tts_engines") or ["unknown"])}
    return sorted(u)


def check(audio_plan: dict, assemble_report: dict, root: str = ROOT) -> dict:
    table = entries()
    rows, missing = [], []
    for a in used_assets(audio_plan, assemble_report):
        ent = table.get(a)
        ok = bool(ent) and os.path.exists(os.path.join(root, ent["proof"])) and all(k in ent for k in ("source", "licence", "attribution_required", "proof"))
        if not ok:
            missing.append(a)
        rows.append({"asset": a, **(ent or {"licence": None})})
    attributions = sorted({r["asset"] for r in rows if r.get("attribution_required")})
    return {"ok": not missing, "missing": missing, "assets": rows, "attribution_required_for": attributions,
            "attribution_text": "" if not attributions else "Audio credits: see docs/LICENCES.md"}


def write_docs(root: str = ROOT) -> None:
    table = entries()
    json.dump(table, open(os.path.join(root, "library", "audio_licences.json"), "w", encoding="utf-8"), indent=1)
    lines = ["# Audio licences (generated by `python -m factory.licence --write`)", "",
             "Every audio asset of every video must appear here or delivery fails (factory/licence.py, finalize gate).", "",
             "| Asset | Source | Licence | Attribution | Proof |", "|---|---|---|---|---|"]
    for k, v in table.items():
        lines.append(f"| {k} | {v['source']} | {v['licence']} | {'yes' if v['attribution_required'] else 'no'} | {v['proof']} |")
    lines += ["", "Notes:", "- Music, ambience and SFX are synthesised by our own code from noise and oscillators; no third-party recording, sample or loop is used, so no Content ID match is possible.",
              "- Voice: Chatterbox (MIT). The Perth watermark is applied at generation and never disabled; it was NOT re-detected after our voice chain, reverb, loudnorm and AAC encode.",
              "- The ASR model (Moonshine via sherpa-onnx) only checks the voice and is not part of the video audio.",
              "- If a future asset needs attribution, `attribution_text` in qa/licence_report.json is appended to the YouTube description file in the repo."]
    open(os.path.join(root, "docs", "LICENCES.md"), "w", encoding="utf-8").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    if "--write" in sys.argv:
        write_docs()
        print("wrote docs/LICENCES.md and library/audio_licences.json")
